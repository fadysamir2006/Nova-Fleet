// Downloads the open-license UI fonts used by Nova Fleet into public/fonts.
// Run once with: node scripts/fetch-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';

const OUT = path.join(process.cwd(), 'public', 'fonts');
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0 Safari/537.36';

const KEEP = new Set(['latin', 'latin-ext', 'arabic']);

const families = [
  { google: 'Rajdhani:wght@500;600;700', family: 'Rajdhani', slug: 'rajdhani' },
  { google: 'Share+Tech+Mono', family: 'Share Tech Mono', slug: 'share-tech-mono' },
  { google: 'Noto+Kufi+Arabic:wght@400;600;700', family: 'Noto Kufi Arabic', slug: 'noto-kufi-arabic' },
];

const download = async (url) => {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return Buffer.from(await res.arrayBuffer());
};

let manifest = '/* Generated by scripts/fetch-fonts.mjs — all families are SIL OFL 1.1. */\n\n';

for (const family of families) {
  const cssUrl = `https://fonts.googleapis.com/css2?family=${family.google}&display=swap`;
  const res = await fetch(cssUrl, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`CSS ${res.status} for ${family.slug}`);
  const css = await res.text();

  const faceRe = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
  let match;
  let count = 0;
  console.log(`\n${family.slug}`);

  while ((match = faceRe.exec(css))) {
    const subset = match[1];
    if (!KEEP.has(subset)) continue;
    const body = match[2];
    const urlMatch = body.match(/url\((https:\/\/[^)]+\.woff2)\)/);
    if (!urlMatch) continue;
    const weight = (body.match(/font-weight:\s*(\d+)/) || [])[1] || '400';
    const style = (body.match(/font-style:\s*(\w+)/) || [])[1] || 'normal';
    const range = (body.match(/unicode-range:\s*([^;]+);/) || [])[1];
    const file = `${family.slug}-${subset}-${weight}.woff2`;
    const target = path.join(OUT, file);
    if (!fs.existsSync(target)) fs.writeFileSync(target, await download(urlMatch[1]));
    console.log(`  ${file}`);
    manifest += `@font-face {\n  font-family: '${family.family}';\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: swap;\n  src: url('${file}') format('woff2');${range ? `\n  unicode-range: ${range};` : ''}\n}\n\n`;
    count += 1;
  }
  if (count === 0) throw new Error(`no faces for ${family.slug}`);
}

fs.writeFileSync(path.join(OUT, 'fonts.css'), manifest);
console.log('\nWrote public/fonts/fonts.css');
