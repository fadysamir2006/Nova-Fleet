export const DICTIONARIES: Record<Lang, Record<StringKey, string>> = {
  en: EN as Record<StringKey, string>,
  ar: AR,
};

const LANG_KEY = 'nova-fleet-lang';

export class I18n {
  private listeners = new Set<(lang: Lang) => void>();
  public lang: Lang;

  constructor() {
    this.lang = this.detectLanguage();
    this.applyDocumentLanguage();
  }

  private detectLanguage(): Lang {
    try {
      const saved = localStorage.getItem(LANG_KEY);
      if (saved === 'en' || saved === 'ar') return saved;
    } catch {
      // Storage can be unavailable in private/embedded contexts.
    }
    return navigator.language.toLowerCase().startsWith('ar') ? 'ar' : 'en';
  }

  public setLanguage(lang: Lang): void {
    if (lang === this.lang) return;
    this.lang = lang;
    try {
      localStorage.setItem(LANG_KEY, lang);
    } catch {
      // Ignore storage errors.
    }
    this.applyDocumentLanguage();
    for (const listener of this.listeners) listener(lang);
  }

  public toggle(): Lang {
    const next: Lang = this.lang === 'en' ? 'ar' : 'en';
    this.setLanguage(next);
    return next;
  }

  public get dir(): 'ltr' | 'rtl' {
    return this.lang === 'ar' ? 'rtl' : 'ltr';
  }

  public t(key: StringKey, values?: Record<string, string | number>): string {
    const dictionary = DICTIONARIES[this.lang] as Record<string, string | undefined>;
    const fallback = EN as Record<string, string | undefined>;
    let text = dictionary[key] ?? fallback[key];
    if (text === undefined) {
      if (import.meta.env.DEV) {
        console.warn(`[Nova Fleet] Missing i18n key "${key}" (${this.lang}).`);
      }
      const tail = String(key).split('.').pop() ?? String(key);
      text = tail.replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase());
    }
    if (values) {
      for (const [name, value] of Object.entries(values)) {
        text = text.replaceAll(`{${name}}`, String(value));
      }
    }
    return text;
  }

  /** True when a key exists in both dictionaries. Used by the i18n guard script. */
  public has(key: string): boolean {
    return key in EN && key in AR;
  }

  public resourceLabel(
    key: 'ferrite' | 'aurium' | 'cryonite' | 'magmarite' | 'hexite' | 'thryxium' | 'nanocarbon' | 'isotopes' | 'alloys',
  ): string {
    return this.t(`resource.${key}` as StringKey);
  }

  public onChange(listener: (lang: Lang) => void): () => void {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  }

  private applyDocumentLanguage(): void {
    document.documentElement.lang = this.lang;
    document.documentElement.dir = this.dir;
    document.title =
      this.lang === 'ar' ? 'أسطول نوفا // Nova Fleet' : 'Nova Fleet // أسطول نوفا';
  }
}

export const getSavedLang = (): Lang | null => {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    return saved === 'ar' || saved === 'en' ? saved : null;
  } catch {
    return null;
  }
};

export type { StringKey };
